from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
_T = tomllib.loads((REPO / "tools" / "target.toml.in").read_text(encoding="utf-8"))

ENGINE: str = _T["engine"]
MANIFEST: str = _T["manifest"]
DECL_DIR: str = _T["decl_dir"]
DATA_KEY_NS: str = _T["data_key_ns"]
ENTRY_ATTR: str = _T["entry_attr"]
PART_ATTR: str = _T["part_attr"]
ENGINES = ("horizon", "sunrise")


def key(name: str) -> str:
    """An engine data key, e.g. key("add_to") -> "sunrise:add_to"."""
    return f"{DATA_KEY_NS}:{name}"


def engine_rs() -> bytes:
    return (
        "//! Generated by tools/gen_decls.py from tools/target.toml.in (RETARGET_PLAN D13). Do not edit.\n"
        "//! The engine's entry and part attributes, so the rest of the crate names no engine.\n"
        f"pub use mod_api::{ENTRY_ATTR} as entry;\n"
        f"pub use mod_api::{PART_ATTR} as part;\n"
    ).encode()
